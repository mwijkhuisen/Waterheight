// Regenerates registry/rivernet.yaml (P6b): every registry station placed on the
// river graph of the COMMITTED fixture (tools/geo/fixtures/rivernet.*), with the
// same code geo.yml runs (tools/geo/rivernet/place.ts), and the public reaches.
// The registry sync in `migrate` stores it (river, reach, km_official and its
// label, km_to_nl_entry, nl_entry_node); km_graph stays in the file.
//
//   node scripts/gen-rivernet.ts            # rewrite registry/rivernet.yaml
//   node scripts/gen-rivernet.ts --check    # exit 1 if the committed file differs
//
// registry/travel-empirical.yaml (P14f) is read too: its pairs set the travel time of a reach, so a data PR that
// fills it changes the reaches here (the shipped file is empty and changes nothing).
//
// A newer geo release is adopted by refreshing the fixture from that run's
// `rivernet-fixture` artifact, updating FIXTURE_RUN and running this script
// (docs/runbooks/geo-refresh.md). Owner-audience rows appear as the station
// registry identifies them: id, river, reach and km (invariant 11).

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { type RivernetFile, validateRivernet } from '../packages/contracts/src/rivernet.ts';
import { buildFromFiles, readRivers } from '../tools/geo/rivernet/build.ts';
import { place, readEmpirical, readOverrides } from '../tools/geo/rivernet/place.ts';
import { readStations } from '../tools/geo/rivernet/stations.ts';
import { loadWaterbodyInput, readWaterbodies } from '../tools/geo/rivernet/waterbodies.ts';

const root = join(import.meta.dirname, '..');
const FX = join(root, 'tools/geo/fixtures');
export const FIXTURE_RUN = 'https://github.com/mwijkhuisen/Waterheight/actions/runs/39154893388';
export const RIVERNET_PATH = join(root, 'registry/rivernet.yaml');
/** P17b: the committed water-body fixture (the osmium export of the water-body ids), plain or gzipped. */
const WATERBODY_FIXTURES = ['rivernet.waterbodies.geojsonseq', 'rivernet.waterbodies.geojsonseq.gz'].map((f) =>
  join(FX, f),
);

const HEADER = `# GENERATED by scripts/gen-rivernet.ts from the committed river-graph fixture, registry/rivers.yaml,
# registry/snap-overrides.yaml, registry/waterbodies.yaml with the committed water-body fixture, and
# registry/stations/ (P6b, P17b, ADR-0012). Do not edit: change the inputs and run it again (CI fails on a
# difference). Read by the registry sync in \`migrate\`, never by readRegistry.
# stations: every registry station; rule = how it was placed (override, name, official_km), on a canal's
#   edge (canal_edge: \`canal\` names the canal; no river, reach or chainage) or why not (canal, unsnapped,
#   no_coordinates, water_not_in_rivers, no_edge_within_500m); km_official is the operator's km
#   (km_official_system its label), km_graph the km along its river from the river's sources,
#   km_to_nl_entry the km to its NL entry node (negative below it). waterbody: its water body by identity
#   (a reviewed override or an exact published name, never geometry alone), waterbody_rule how
#   (waterbody_contains, waterbody_shore, waterbody_named; waterbody_too_far: identified but too far from the
#   polygon, so none); all null while fixture.waterbodies_sha256 is null. Owner-audience rows identify the
#   station only (river, reach, km, canal, water body). reaches: cut at public stations only; id <river>.<seq>.
`;

export async function generate(): Promise<string> {
  const ways = join(FX, 'rivernet.ways.geojsonseq');
  const build = await buildFromFiles({
    ways,
    relations: join(FX, 'rivernet.relations.opl'),
    provenance: join(FX, 'rivernet.provenance.json'),
  });
  const rivers = readRivers();
  // P17b: the water bodies, with their polygons from the committed water-body fixture once it exists; without it no
  // station gets a body (a polygon body needs its area).
  const bodies = readWaterbodies(rivers);
  const areas = WATERBODY_FIXTURES.find((p) => existsSync(p));
  const waterbodies = areas === undefined ? null : await loadWaterbodyInput(bodies, areas);
  const placed = place(
    build.edges,
    rivers,
    readStations(),
    readOverrides(rivers, bodies),
    readEmpirical(),
    waterbodies,
  );
  const osm = (build.graph as { osm: { replication_timestamp: string } }).osm.replication_timestamp;
  const sha256 = (path: string) => createHash('sha256').update(readFileSync(path)).digest('hex');
  const file: RivernetFile = {
    version: 1,
    fixture: {
      source_run: FIXTURE_RUN,
      ways_sha256: sha256(ways),
      osm_replication_timestamp: osm,
      waterbodies_sha256: waterbodies === null || areas === undefined ? null : sha256(areas),
    },
    stations: [...placed.stations]
      .sort((a, b) => (a.id < b.id ? -1 : 1))
      .map((s) => ({
        id: s.id,
        rule: s.rule,
        river: s.river,
        reach: s.reach,
        km_official: s.km_official,
        km_official_system: s.km_official_system,
        km_graph: s.km_graph,
        km_to_nl_entry: s.km_to_nl_entry,
        nl_entry_node: s.nl_entry_node,
        canal: s.canal,
        waterbody: s.waterbody,
        waterbody_rule: s.waterbody_rule,
      })),
    reaches: placed.reaches.map((r) => ({
      id: r.id,
      river: r.river,
      seq: r.seq,
      up_station: r.up_station,
      down_station: r.down_station,
      length_km: Math.round(r.length_m) / 1000,
      flags: r.flags,
      travel_time_h: r.travel_time_h,
      travel_time_source: r.travel_time_source,
    })),
  };
  const { problems } = validateRivernet(file);
  if (problems.length > 0) throw new Error(`gen-rivernet: ${problems.slice(0, 5).join('; ')}`);
  // One JSON flow mapping per line: valid YAML, diffable per station and reach.
  const lines = (rows: readonly object[]) => rows.map((r) => `  - ${JSON.stringify(r)}\n`).join('');
  return `${HEADER}version: 1\nfixture: ${JSON.stringify(file.fixture)}\nstations:\n${lines(file.stations)}reaches:\n${lines(file.reaches)}`;
}

if (import.meta.main) {
  const text = await generate();
  if (!process.argv.includes('--check')) writeFileSync(RIVERNET_PATH, text);
  else if (readFileSync(RIVERNET_PATH, 'utf8') !== text) {
    console.error('gen-rivernet: registry/rivernet.yaml is stale; run node scripts/gen-rivernet.ts');
    process.exitCode = 1;
  }
}
